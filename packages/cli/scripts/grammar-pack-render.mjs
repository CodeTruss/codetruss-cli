/**
 * The exact text of the two files the grammar release GENERATES.
 *
 * Shared by `build-grammar-packs.mjs`, which writes them, and
 * `verify-grammar-packs.mjs`, which re-derives them from the published bytes and
 * compares. One renderer is the point: a verifier that re-implements the format
 * eventually disagrees with the generator over whitespace and gets loosened
 * until it proves nothing. Comparing whole files instead of hunting for expected
 * substrings is what makes the check total — it fails on a digest bound to the
 * wrong name, on an entry nobody published, and on any hand edit to a file whose
 * header says not to edit it by hand.
 */

/**
 * What the CLI's loader does with each artifact.
 *
 * Roles exist because the loader used to pick the grammar with
 * `files.find(f => f.name.startsWith('tree-sitter-'))` — the FIRST match. A pack
 * carrying an extra `tree-sitter-evil.wasm` ordered ahead of the real grammar
 * would have had it loaded as the grammar. Every artifact now says what it is,
 * and the loader requires exactly one artifact per role, so "whichever matched
 * the name shape first" is not a question that can be asked.
 */
export const GRAMMAR_FILE_ROLES = ['runtime', 'runtime-wasm', 'grammar']

/**
 * The published index at `/downloads/grammars/codetruss-grammars-latest.json`.
 *
 * Deliberately carries no `role`. This file is the site's record of what exists,
 * where, how large and with which digest; role is an instruction to the CLI's
 * loader, and the CLI never fetches this file — it ships the pin instead. Adding
 * a field with no consumer would rewrite bytes already served for nothing.
 */
export function renderGrammarSiteManifest(packs) {
  const published = packs.map((pack) => ({
    ...pack,
    files: pack.files.map((file) => ({
      name: file.name,
      url: file.url,
      bytes: file.bytes,
      sha256: file.sha256,
    })),
  }))
  return `${JSON.stringify({ packs: published }, null, 2)}\n`
}

/**
 * The compiled-in pin, `packages/cli/src/grammar-pack-manifest.ts`.
 *
 * Generated rather than hand-maintained because a hand-copied digest is a digest
 * that eventually disagrees with the bytes, and this one is the only thing
 * standing between a user and executing whatever a compromised origin served.
 */
export function renderGrammarPin(packs) {
  const pinned = packs.map((pack) => ({
    ...pack,
    files: pack.files.map((file) => ({
      name: file.name,
      role: file.role,
      url: file.url,
      bytes: file.bytes,
      sha256: file.sha256,
    })),
  }))
  return `/**
 * Pinned grammar-pack digests. GENERATED by scripts/build-grammar-packs.mjs.
 *
 * Do not edit by hand. These digests are what \`codetruss grammars install\`
 * checks a download against, and what every subsequent load re-checks on disk.
 * A pack whose bytes do not hash to exactly these values is never loaded, and
 * the run discloses Python as skipped instead.
 *
 * \`pnpm grammars:verify\` re-derives this entire file from the published
 * artifacts and compares it byte for byte, so an edit here — a digest moved to
 * another name, an artifact nobody published, a fourth entry — fails the build
 * rather than shipping.
 */

/** What the loader does with an artifact. Exactly one artifact per role, per pack. */
export type GrammarFileRole = ${GRAMMAR_FILE_ROLES.map((role) => `'${role}'`).join(' | ')}

export interface PinnedGrammarFile {
  name: string
  role: GrammarFileRole
  /** Path under the downloads origin, e.g. \`/downloads/grammars/python-1.0.0/…\`. */
  url: string
  bytes: number
  sha256: string
}

export interface PinnedGrammarPack {
  name: string
  version: string
  /** The \`SastLanguage\` this pack enables. */
  language: string
  runtime: { package: string; version: string }
  grammar: { package: string; version: string }
  files: PinnedGrammarFile[]
}

export const PINNED_GRAMMAR_PACKS: readonly PinnedGrammarPack[] = ${JSON.stringify(pinned, null, 2)}

/** Pack names this CLI build knows how to install. */
export const GRAMMAR_PACK_NAMES: readonly string[] = PINNED_GRAMMAR_PACKS.map((pack) => pack.name)

export function pinnedGrammarPack(name: string): PinnedGrammarPack | undefined {
  return PINNED_GRAMMAR_PACKS.find((pack) => pack.name === name)
}
`
}
